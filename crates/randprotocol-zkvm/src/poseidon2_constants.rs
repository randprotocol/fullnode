//! The width-8 Goldilocks Poseidon2 round constants, as a literal table (audit finding ZKV-2;
//! since constraint set 11 the Grain derivation, ZKVM-107).
//!
//! Every Poseidon2 hash this zkVM computes — the Merkle commitments and the Fiat–Shamir
//! challenger (`machine::permutation`), the in-circuit `poseidon2` chip's preprocessed round
//! constants (`tables::poseidon2::round_constants`), the program/input/public digests
//! (`hash.rs`), and `rand-zkvm-cuda`'s GPU and CPU-twin Merkle engines — reads the numbers
//! below and nothing else. `rand-zkvm-cuda` has no dependency on this crate (the dependency runs
//! the other way), so it compiles this very file into itself with a `#[path]` module
//! (`rand-zkvm-cuda/src/constants.rs`): one table, two crates, no copy. That is why this file
//! names only `p3_*` and `rand` paths, never `crate::` — and why the tests that need this crate
//! (the Grain re-derivation, the chip's own arithmetic) live in `poseidon2_grain.rs` instead.
//!
//! ## Where the numbers come from
//!
//! They are the output of the Poseidon paper's Grain LFSR for the parameters of this
//! permutation and nothing else — field type 1 (prime), S-box 0 (`x^alpha`, here `x^7`),
//! `n = 64`, `t = 8`, `R_F = 8`, `R_P = 22` — as `poseidon2_grain.rs` documents step by step.
//! There is no seed to choose. Three things pin the table:
//!
//! - `poseidon2_grain`'s `the_table_is_the_grain_derivation` re-runs the generator and compares
//!   all 86 values;
//! - `tools/poseidon2_grain/grain.py --check` is a second implementation (standard-library
//!   Python) that does the same without building the crate;
//! - `tests::the_table_is_the_one_plonky3_ships` (below) compares with `p3-goldilocks 0.7.0`'s
//!   `GOLDILOCKS_POSEIDON2_RC_8_{EXTERNAL_INITIAL, INTERNAL, EXTERNAL_FINAL}`, which upstream
//!   documents as "Generated by the Grain LFSR with parameters: field_type=1, alpha=7
//!   (exp_flag=0), n=64, t=8, R_F=8, R_P=22". The two derivations were written independently
//!   and agree, so this permutation is `p3-goldilocks`'s default width-8 one, the one external
//!   cryptanalysis of Plonky3's Goldilocks Poseidon2 is about.
//!
//! The linear layers are not constants of this file: the external layer is the Poseidon2
//! paper's `M4`-circulant matrix and the internal layer is `p3-goldilocks`'s
//! `MATRIX_DIAG_8_GOLDILOCKS` (`tables::poseidon2::{mds_light, internal_matmul}`), and the round
//! numbers are `(8, 22)` with `x^7`.
//!
//! ## History
//!
//! Through constraint set 10 the table was a development draw:
//! `Poseidon2Goldilocks::<8>::new_from_rng_128(&mut StdRng::seed_from_u64(0x5261_6e64_5a4b))`
//! ("RandZK"), printed once and committed (ZKV-2) so a `rand` release could not change it.
//! Constraint set 11 replaced it with the table below (ZKVM-107, `docs/05-roadmap.md`), which
//! moved every Poseidon2 output — every program digest, key, root, commitment and genesis.
use p3_goldilocks::{Goldilocks, Poseidon2Goldilocks};
use p3_poseidon2::ExternalLayerConstants;

/// An opaque tag, not a seed. Nothing derives constants from it: since constraint set 11 the
/// table is the Grain derivation, which has no seed. It keeps the value it had as the seed of the
/// development draw (`0x5261_6e64_5a4b`, "RandZK") only because `rand-zkvm-cuda`'s engines are
/// keyed on it (`constants::permutation(seed)`, `CpuHashEngine::new`, `GpuProver::probe`,
/// `gpu/ntt.rs::DEFAULT_PERM_SEED`, `recursion`'s `machine/backend.rs::PERM_SEED`): that tag
/// selects this committed table, and any other value selects a `StdRng` draw for that crate's own
/// tests. Renaming it would touch every engine constructor for no change in behaviour.
pub const PERM_SEED: u64 = 0x5261_6e64_5a4b;


